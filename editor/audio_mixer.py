AUDIO_EXTENSIONS = {".mp3", ".wav", ".m4a", ".ogg"}


def _generate_original_fight_music(music_dir: Path):
    """Synthesize an original, energetic cinematic action bed with no third-party samples."""
    music_dir.mkdir(parents=True, exist_ok=True)
    output = music_dir / "project_original_fight_music.wav"

    # Fast low drum pulses, sharp synthetic hits, a driving bass ostinato and
    # tense minor-key tones. This is original synthesized audio, not a song sample.
    expression = (
        "0.22*sin(2*PI*55*t)*(0.5+0.5*cos(2*PI*2*t))"
        "+0.16*sin(2*PI*82.41*t)*(0.5+0.5*cos(2*PI*2*t))"
        "+0.09*sin(2*PI*110*t)*(0.5+0.5*sin(2*PI*4*t))"
        "+0.055*sin(2*PI*164.81*t)*(0.55+0.45*sin(2*PI*3*t))"
        "+0.045*sin(2*PI*196*t)*(0.55+0.45*sin(2*PI*3*t))"
        "+0.035*sin(2*PI*233.08*t)*(0.55+0.45*sin(2*PI*1.5*t))"
        r"+0.18*sin(2*PI*48*t)*exp(-mod(t\,0.5)*16)"
        r"+0.07*sin(2*PI*1400*t)*exp(-mod(t+0.25\,0.5)*24)"
        r"+0.025*sin(2*PI*3200*t)*exp(-mod(t+0.25\,0.5)*30)"
    )
    subprocess.run(
        [
            "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
            "-f", "lavfi", "-i", f"aevalsrc={expression}:s=44100:d=180",
            "-af", "highpass=f=35,lowpass=f=9000,afade=t=in:st=0:d=1.2,afade=t=out:st=175:d=5,loudnorm=I=-16:TP=-1.5:LRA=7",
            "-c:a", "pcm_s16le", str(output),
        ],
        check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60
    )
    metadata = {
        "title": "Original Cinematic Fight Instrumental",
        "creator": "Generated by Movie Reels Publisher",
        "source_url": "Generated locally by FFmpeg synthesizer; no third-party samples",
        "license_url": "Original project-generated audio; no third-party recording or samples",
        "kind": "original_generated_action_music",
        "genre": "cinematic action fight instrumental",
    }
    return output, metadata


def choose_fighting_music(music_dir: Path):
    """Use only a verified track explicitly identified as action/fight music; otherwise synthesize one."""
    music_dir.mkdir(parents=True, exist_ok=True)
    tracks = []
    for path in music_dir.iterdir():
        if path.suffix.lower() not in AUDIO_EXTENSIONS or path.name.startswith("project_original_"):
            continue
        sidecar = Path(str(path) + ".license.json")
        if not sidecar.exists():
            continue
        try:
            metadata = json.loads(sidecar.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        required = ("title", "creator", "source_url", "license_url")
        if not all(str(metadata.get(field, "")).strip() for field in required):
            continue
        genre = " ".join(str(metadata.get(k, "")) for k in ("genre", "mood", "tags")).lower()
        if license_is_allowed(metadata.get("license_url", "")) and any(
            term in genre for term in ("action", "fight", "combat", "cinematic")
        ):
            tracks.append((path, metadata))
    if tracks:
        return random.choice(tracks)
    return _generate_original_fight_music(music_dir)
